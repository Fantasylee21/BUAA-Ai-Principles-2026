processor = AutoProcessor.from_pretrained(MODEL_ID, min_pixels=256 * 28 * 28, max_pixels=512 * 28 * 28)
model = Qwen2_5_VLForConditionalGeneration.from_pretrained(MODEL_ID, torch_dtype=torch.float16, device_map="auto", attn_implementation="sdpa").eval()
labels = {"positive", "negative", "neutral"}
def normalize_response(raw):
    obj = {}
    match = re.search(r"\{.*?\}", raw, flags=re.S)
    if match:
        try:
            obj = json.loads(match.group(0))
        except Exception:
            obj = {}
    if obj:
        emotion = str(obj.get("pred_emotion", "neutral")).lower().strip()
        uncertain_raw = str(obj.get("is_uncertain", "no")).lower().strip()
        question = str(obj.get("clarifying_question", "none")).strip()
    else:
        low = raw.lower()
        found = [label for label in labels if re.search(r"\b" + label + r"\b", low)]
        emotion = found[0] if len(found) == 1 else "neutral"
        uncertain_raw = "yes" if re.search(r"\b(yes|uncertain|unclear|insufficient|conflict|cannot determine|can't tell)\b", low) else "no"
        question = "Could you clarify how you felt during this moment?"
    if emotion not in labels:
        emotion = "neutral"
    uncertain = "yes" if uncertain_raw in {"yes", "y", "true", "1"} else "no"
    if uncertain == "no":
        question = "none"
    elif question.lower() in {"none", "null", "n/a", ""}:
        question = "Could you clarify how you felt during this moment?"
    return emotion, uncertain, question
@torch.inference_mode()
def infer_one(row):
    prompt = "Judge overall emotion from this video and supplied dialogue: " + str(row.get("text", "")) + "\nChoose positive, negative, or neutral. If visual and dialogue evidence conflict or is insufficient, use is_uncertain=yes and ask one brief neutral question; otherwise use no and none. Return only JSON with keys pred_emotion, is_uncertain, clarifying_question."
    messages = [{"role": "user", "content": [{"type": "video", "video": row["video_path"], "fps": 1.0}, {"type": "text", "text": prompt}]}]
    text = processor.apply_chat_template(messages, tokenize=False, add_generation_prompt=True)
    image_inputs, video_inputs = process_vision_info(messages)
    inputs = processor(text=[text], images=image_inputs, videos=video_inputs, padding=True, return_tensors="pt", cap_pixels_per_frame=True).to(model.device)
    output_ids = model.generate(**inputs, max_new_tokens=100, do_sample=False, use_cache=True)
    raw = processor.batch_decode(output_ids[:, inputs["input_ids"].shape[1]:], skip_special_tokens=True)[0]
    emotion, uncertain, question = normalize_response(raw)
    return {"sample_id": row["sample_id"], "pred_emotion": emotion, "is_uncertain": uncertain, "clarifying_question": question, "raw_response": raw}
